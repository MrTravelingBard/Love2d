#!/usr/bin/env node
// tools/p8-convert.js
// Extracts the spritesheet and map from a PICO-8 .p8 cart. No dependencies (Node 18+).
//
// usage:
//   node tools/p8-convert.js <cart.p8> <src-dir> [--shared-map]
//
// writes:
//   <src-dir>/assets/sheet.png   128x128 spritesheet, color 0 transparent
//   <src-dir>/data/map.lua       map tiles, trimmed to the used area
//
// --shared-map also reads map rows 32-63 out of the lower half of the spritesheet
// (PICO-8 shares that memory). Only needed if your map uses those rows.

const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const PALETTE = [
	"000000", "1D2B53", "7E2553", "008751", "AB5236", "5F574F", "C2C3C7", "FFF1E8",
	"FF004D", "FFA300", "FFEC27", "00E436", "29ADFF", "83769C", "FF77A8", "FFCCAA",
].map((h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)));

// ---- args ----
const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const sharedMap = process.argv.includes("--shared-map");
if (args.length < 2) {
	console.error("usage: node tools/p8-convert.js <cart.p8> <src-dir> [--shared-map]");
	process.exit(1);
}
const [cartPath, srcDir] = args;

// ---- read sections ----
const lines = fs.readFileSync(cartPath, "utf8").split(/\r?\n/);
function section(name) {
	const start = lines.indexOf(`__${name}__`);
	if (start < 0) return [];
	const out = [];
	for (let i = start + 1; i < lines.length && !/^__\w+__$/.test(lines[i]); i++) {
		if (lines[i].length) out.push(lines[i]);
	}
	return out;
}

// ---- spritesheet: 128 rows x 128 pixels, one hex digit per pixel ----
const gfx = Array.from({ length: 128 }, () => new Array(128).fill(0));
section("gfx").slice(0, 128).forEach((row, y) => {
	for (let x = 0; x < 128; x++) {
		const c = row[x];
		gfx[y][x] = c ? parseInt(c, 16) : 0;
	}
});

// ---- PNG writer ----
const crcTable = new Uint32Array(256).map((_, n) => {
	let c = n;
	for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
	return c >>> 0;
});
function crc32(buf) {
	let c = 0xffffffff;
	for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
	return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
	const len = Buffer.alloc(4);
	len.writeUInt32BE(data.length);
	const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
	const crc = Buffer.alloc(4);
	crc.writeUInt32BE(crc32(td));
	return Buffer.concat([len, td, crc]);
}
function encodePng(w, h, rgba) {
	const ihdr = Buffer.alloc(13);
	ihdr.writeUInt32BE(w, 0);
	ihdr.writeUInt32BE(h, 4);
	ihdr[8] = 8; // bit depth
	ihdr[9] = 6; // RGBA
	const raw = Buffer.alloc((w * 4 + 1) * h);
	for (let y = 0; y < h; y++) {
		raw[y * (w * 4 + 1)] = 0; // filter: none
		rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
	}
	return Buffer.concat([
		Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
		chunk("IHDR", ihdr),
		chunk("IDAT", zlib.deflateSync(raw)),
		chunk("IEND", Buffer.alloc(0)),
	]);
}

const rgba = Buffer.alloc(128 * 128 * 4);
for (let y = 0; y < 128; y++) {
	for (let x = 0; x < 128; x++) {
		const c = gfx[y][x];
		const o = (y * 128 + x) * 4;
		rgba[o] = PALETTE[c][0];
		rgba[o + 1] = PALETTE[c][1];
		rgba[o + 2] = PALETTE[c][2];
		rgba[o + 3] = c === 0 ? 0 : 255; // color 0 is transparent in sprites
	}
}
const pngPath = path.join(srcDir, "assets", "sheet.png");
fs.mkdirSync(path.dirname(pngPath), { recursive: true });
fs.writeFileSync(pngPath, encodePng(128, 128, rgba));

// ---- map: 128 x 64 tiles, two hex digits per tile ----
const map = Array.from({ length: 64 }, () => new Array(128).fill(0));
section("map").slice(0, 32).forEach((row, y) => {
	for (let x = 0; x < 128; x++) {
		const hex = row.slice(x * 2, x * 2 + 2);
		map[y][x] = hex.length === 2 ? parseInt(hex, 16) : 0;
	}
});
if (sharedMap) {
	// map rows 32-63 live in the same memory as spritesheet rows 64-127.
	// within a byte, the low nibble is the LEFT pixel.
	for (let y = 32; y < 64; y++) {
		for (let x = 0; x < 128; x++) {
			const gy = 64 + (y - 32) * 2 + (x >= 64 ? 1 : 0);
			const gx = (x % 64) * 2;
			map[y][x] = gfx[gy][gx + 1] * 16 + gfx[gy][gx];
		}
	}
}

// trim to the used area (origin stays at 0,0)
let width = 0, height = 0;
map.forEach((row, y) => row.forEach((t, x) => {
	if (t !== 0) { width = Math.max(width, x + 1); height = Math.max(height, y + 1); }
}));

const rowsLua = map.slice(0, height).map((row, y) =>
	`\t\t{ ${row.slice(0, width).join(",")} }, -- y=${y}`
).join("\n");

const lua = `-- data/map.lua
-- GENERATED by tools/p8-convert.js from ${path.basename(cartPath)}. Do not edit by hand.
-- Tile numbers are PICO-8 sprite indices. 0 = empty (not drawn).
-- rows[y+1][x+1] holds the tile at map position (x, y); anything outside is 0.
return {
	width = ${width},
	height = ${height},
	rows = {
${rowsLua}
	},
}
`;
const luaPath = path.join(srcDir, "data", "map.lua");
fs.mkdirSync(path.dirname(luaPath), { recursive: true });
fs.writeFileSync(luaPath, lua);

console.log(`wrote ${pngPath}`);
console.log(`wrote ${luaPath} (${width}x${height} tiles)`);
